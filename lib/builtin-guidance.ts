export function builtinGuidance(context:StudioContext,profile:QualityProfile,action:'questions'|'generate'|'evaluate'):string{
  const domain=context.type==='code'?CODE:profile.kind==='image'?IMAGE:profile.kind==='video'?VIDEO:'';
  const phase=action==='questions'?'【本轮使用方式】从适用维度中挑最影响结果且尚未回答的缺口提问，遵循既有题数和难度。不要把整张清单逐项问一遍。'
    :action==='generate'?'【本轮使用方式】把适用维度写成具体、可直接使用的内容，不留下待填变量或模板说明；保留既有JSON契约与视觉计划格式，已确认要求始终优先。'
    :'【本轮使用方式】这些原则仅作为当前稿的相关审阅标准，不改写提示词、不重新提问、不输出生成契约。非必要的缺省项不能当成错误；问题引用仍须匹配原文，未执行的效果不能声称已验证。';
  return [COMMON,domain,phase].filter(Boolean).join('\n');
}
