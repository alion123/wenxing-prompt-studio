结合任务确定运行环境、现有技术栈和交付形式，优先复用用户已有项目。未指定技术且需要选择时，将选择列为建议或假设；不默认绑定某个框架、数据库、云服务或付费接口。
关注真正相关的边界：空输入、非法输入、加载失败、异常提示、数据持久化和恢复。涉及用户输入、权限、密钥或外部请求时写清相应处理；不硬塞与任务无关的架构和流程。
